"""Exercise package installation with fake makepkg/pacman, without privilege."""

import os
import subprocess
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]


@pytest.mark.parametrize("generated_launcher", [True, False])
def test_arch_install_registers_archive_and_migrates_only_our_launcher(tmp_path, generated_launcher):
    repo = tmp_path / "checkout with spaces"
    repo.mkdir()
    archive = repo / "kizurium-translator-1.3.0-1-x86_64.pkg.tar.zst"
    archive.touch()
    bin_dir = tmp_path / "bin"
    bin_dir.mkdir()
    launcher = bin_dir / "kizurium-translator"
    launcher.write_text("# Generated by kizurium-translator install.sh\n" if generated_launcher else "# unrelated launcher\n")
    data_home = tmp_path / "data"
    desktop = data_home / "applications/kizurium-translator.desktop"
    desktop.parent.mkdir(parents=True)
    desktop.write_text(f"Exec={launcher}\n")
    source = (ROOT / "install.sh").read_text()
    function = "install_arch_package() {" + source.split("install_arch_package() {", 1)[1].split('\nif [[ "$INSTALL_MODE" == package ]]', 1)[0]
    # Isolate the post-install doctor/runtime command from the real host.
    function = function.replace("/usr/bin/kizurium-translator", "app_command")
    function = function.replace("((EUID == 0))", "false")
    script = '''set -euo pipefail
step() { :; }; ok() { :; }; warn() { :; }; err() { echo "$*" >&2; }
is_tty() { return 1; }
print_hotkey_hint() { :; }
app_command() { :; }
pacman() { return 0; }
makepkg() {
    printf 'makepkg %s\\n' "$*" >> "$CALLS"
    if [[ "$1" == --packagelist ]]; then printf '%s\\n' "$ARCHIVE"; fi
}
sudo() { printf 'sudo'; printf ' <%s>' "$@"; printf '\\n'; }
SYS_PKGS=()
''' + function + "\ninstall_arch_package\n"
    env = {**os.environ, "REPO_DIR": str(repo), "BIN_DIR": str(bin_dir),
           "VENV_DIR": str(tmp_path / "venv"), "XDG_DATA_HOME": str(data_home),
           "CALLS": str(tmp_path / "calls"), "ARCHIVE": str(archive),
           "ASSUME_YES": "1", "PREFIX_SET": "0", "WITH_SYSTEM": "yes",
           "OFFLINE_PACKS": "no", "MEIKI": "no", "PADDLE": "no",
           "EXTRAS": "", "BERGAMOT": "no"}
    result = subprocess.run(["bash", "-c", script], env=env, capture_output=True, text=True)
    assert result.returncode == 0, result.stderr
    assert f"sudo <pacman> <-U> <--noconfirm> <--> <{archive}>" in result.stdout
    assert "makepkg --force --syncdeps --noconfirm" in (tmp_path / "calls").read_text()
    assert launcher.exists() is not generated_launcher
    assert not desktop.exists()


def test_native_update_does_not_require_legacy_saved_options(tmp_path):
    # A validation failure occurs after --update loading. Native update must
    # reach that validation even when no venv/install-options ever existed.
    result = subprocess.run(
        ["bash", str(ROOT / "install.sh"), "--update", "--prefix", str(tmp_path)],
        env={**os.environ, "XDG_DATA_HOME": str(tmp_path / "empty-data")},
        capture_output=True, text=True,
    )
    assert result.returncode == 2
    assert "--prefix доступен только с --user" in result.stdout
    assert "нет сохранённых опций" not in result.stdout


@pytest.mark.parametrize("has_cargo", [True, False])
def test_optional_user_native_build_failure_keeps_the_app_usable(tmp_path, has_cargo):
    source = (ROOT / "install.sh").read_text()
    block = source.split('step "Нативные ускорения Rust"', 1)[1].split('\nif [[ -f "$CONFIG_DIR/config.toml" ]]', 1)[0]
    script = '''set -euo pipefail
have() { [[ "$HAS_CARGO" == yes ]]; }
uv() { echo "native build attempted"; return 1; }
ok() { echo "$*"; }; warn() { echo "$*"; }
''' + block
    result = subprocess.run(["bash", "-c", script], capture_output=True, text=True,
        env={**os.environ, "HAS_CARGO": "yes" if has_cargo else "no",
             "VENV_DIR": str(tmp_path / "venv"), "REPO_DIR": str(tmp_path)})
    assert result.returncode == 0, result.stderr
    if has_cargo:
        assert "native build attempted" in result.stdout
        assert "использует Python-реализацию" in result.stdout
    else:
        assert "нет cargo" in result.stdout
        assert "native build attempted" not in result.stdout
